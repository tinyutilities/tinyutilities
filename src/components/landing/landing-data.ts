// Homepage-voice copy for each category card, keyed by `toolCategories` slug (features/tools/
// tool-data.ts) — deliberately a bit more elaborate than that file's own shorter `description`,
// which is written for the /tools directory page instead. The CATEGORY LIST itself is never
// hardcoded here, though: `features` below is generated by mapping over `toolCategories`, so a
// category can never silently go missing from the homepage the way Audio Tools and File Tools
// once did after being added to the registry but not here.
const categoryCardCopy: Record<string, string> = {
  audio: "Trim, join, and adjust audio clips entirely in your browser.",
  image: "Compress, convert, resize, and optimize images for web and print.",
  pdf: "Merge, split, compress, and prepare documents with less friction.",
  developer: "Format code, inspect data, and speed through common dev tasks.",
  text: "Format, clean, count, and transform text for everyday work.",
  files: "Package files into a ZIP or extract one, right in your browser.",
};

const categoryCardIcon: Record<string, ComponentType<{ className?: string }>> = {
  audio: AudioTrimIcon,
  image: ImageIcon,
  pdf: PdfIcon,
  developer: CodeIcon,
  text: TextIcon,
  files: ArchiveIcon,
};

// Hrefs point at the matching category section on /tools (see the `id`s set in
// ToolsDirectory) — each id is `${category.slug}-tools`.
export const features = toolCategories.map((category) => ({
  title: category.title,
  description: categoryCardCopy[category.slug] ?? category.description,
  Icon: categoryCardIcon[category.slug] ?? ImageIcon,
  href: `/tools#${category.slug}-tools`,
}));

